import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { z } from 'zod';

const key = z
  .string()
  .regex(/^[A-Za-z][A-Za-z0-9_]*$/)
  .refine(
    (value) =>
      !['constructor', 'prototype', 'toString', 'valueOf', 'hasOwnProperty'].includes(value),
    'Reserved field name',
  );
const route = z
  .string()
  .regex(/^\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_-]+$/, 'Use a literal absolute URL path');
const primitive = z.union([z.string(), z.number(), z.boolean()]);
const field = z.union([z.enum(['string', 'number', 'boolean']), z.array(z.string()).min(1)]);
const resource = z
  .object({
    path: route,
    key: key.default('id'),
    id: z.enum(['integer', 'uuid']).default('integer'),
    fields: z.record(key, field),
    writable: z.array(key).default([]),
    required: z.array(key).default([]),
    defaults: z.record(key, primitive).default({}),
    filterBy: z.array(key).default([]),
    operations: z.array(z.enum(['list', 'get', 'create', 'update', 'delete'])).min(1),
  })
  .strict();
const schema = z
  .object({
    name: z.string().trim().min(1).max(100),
    buildDir: z.string().min(1),
    testDir: z.string().min(1),
    testMatch: z.string().min(1),
    server: z
      .object({
        command: z.array(z.string().min(1)).min(1),
        readyPath: route,
        timeoutMs: z.number().int().positive().max(120000).default(20000),
      })
      .strict(),
    apiPrefix: route.default('/api'),
    mountPath: z
      .string()
      .regex(/^\/(?:[A-Za-z0-9_-]+\/)*$/, 'Use / or a directory such as /my-project/')
      .default('/'),
    resources: z.array(resource).default([]),
    reads: z.array(z.object({ path: route, fields: z.array(key).min(1) }).strict()).default([]),
  })
  .strict();
export type Config = z.infer<typeof schema>;
export type Resource = Config['resources'][number];
export type Row = Record<string, string | number | boolean>;
export type Seed = { resources: Record<string, Row[]>; reads: Record<string, Row> };
export type Project = { config: Config; root: string; file: string };

export function matchesType(value: unknown, rule: Resource['fields'][string]): boolean {
  return Array.isArray(rule)
    ? typeof value === 'string' && rule.includes(value)
    : typeof value === rule;
}

export function validateConfig(input: unknown): Config {
  const c = schema.parse(input);
  const paths = [...c.resources, ...c.reads].map((r) => r.path);
  if (!paths.length) throw Error('Declare at least one API resource or read.');
  if (new Set(paths).size !== paths.length) throw Error('API paths must be unique.');
  for (const path of paths) {
    if (!path.startsWith(c.apiPrefix + '/')) throw Error('Route must be under apiPrefix: ' + path);
    if (c.resources.some((r) => r.path !== path && path.startsWith(r.path + '/')))
      throw Error('Ambiguous resource routes: ' + path);
  }
  for (const r of c.resources) {
    if (r.fields[r.key] !== (r.id === 'integer' ? 'number' : 'string'))
      throw Error('Declare the ID field type for ' + r.path);
    for (const name of [...r.writable, ...r.required, ...r.filterBy, ...Object.keys(r.defaults)]) {
      if (!Object.hasOwn(r.fields, name)) throw Error('Unknown field ' + name + ' in ' + r.path);
    }
    if (r.writable.includes(r.key) || Object.hasOwn(r.defaults, r.key))
      throw Error('The primary key is generated by the sandbox.');
    for (const [name, v] of Object.entries(r.defaults)) {
      if (!matchesType(v, r.fields[name]!)) throw Error('Invalid default for ' + name);
    }
    for (const name of r.required) {
      if (
        name !== r.key &&
        !r.writable.includes(name) &&
        !Object.hasOwn(r.defaults, name) &&
        r.operations.includes('create')
      ) {
        throw Error('Required field has no source on create: ' + name);
      }
    }
  }
  return c;
}

export async function loadProject(file: string): Promise<Project> {
  file = resolve(file);
  const { default: input } = await import(pathToFileURL(file).href);
  return { file, root: dirname(file), config: validateConfig(input) };
}
